#!/usr/bin/env node
// Icon generator for the v1.23 redesign (DESIGN.md "Iconography").
//
// Line icons: Kubai Icons (https://github.com/kubai087/kubai-icons, MIT, (c) Kubai087 and contributors;
// licence text in tools/icons/kubai/LICENSE). Each JSON keeps only the stroke-2 outline set w["2"].o:
//   k = "line" | "shell"  -> stroked path (2 wide, round caps/joins, no fill)
//   k = "solid"           -> filled path
//   occ = true            -> the part covers what is under it; Android tints with SRC_IN so it cannot
//                            paint "background" over a line, so lines under an occluding circle are cut
//                            here instead (only sliders uses this).
// Notification / media-card buttons: Material Symbols Rounded, FILL 1, wght 400 (Apache-2.0), copied in
// tools/icons/material/ from google/material-design-icons.
//
// Usage: node tools/icons/gen-icons.mjs   (writes app/src/main/res/drawable/*.xml, prints web paths)
// Never touches the launcher / notification-small / monochrome icons (ic_stat_yiwei, ic_launcher_*, mipmap).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const res = path.join(here, '..', '..', 'app', 'src', 'main', 'res', 'drawable');

// drawable name -> [kubai icon, size dp]
const LINE = {
  ic_arrow_back_white: ['arrow-left', 24],
  ic_chevron_right: ['chevron-right', 20],
  ic_check: ['check', 24],
  ic_close_white: ['x', 24],
  ic_set_play: ['play-circle', 24],
  ic_set_bg: ['headphones', 24],
  ic_set_home: ['home', 24],
  ic_set_palette: ['palette', 24],
  ic_set_cloud: ['shield-check', 24],
  ic_block_white: ['ban', 24],
  ic_hide_white: ['eye-off', 24],
  ic_link_white: ['link', 24],
  ic_more_white: ['more-horizontal', 24],
  ic_watch_later_white: ['clock', 24],
  ic_wifi_off_white: ['wifi-off', 24],
  ic_tune_white: ['sliders', 24],
  ic_search: ['search', 24],
  ic_cloud_download: ['cloud-download', 24],
  ic_monitor_off: ['monitor-off', 24],
  ic_lock: ['lock', 24],
  ic_repeat_one: ['repeat-1', 24],
  ic_rotate_ccw: ['rotate-ccw', 24],
  ic_rotate_cw: ['rotate-cw', 24],
  ic_bell_off: ['bell-off', 24],
};
// launcher shortcuts: white disc, brand-red glyph (resource colours, not Ui tokens)
const SHORTCUT = { ic_sc_subs: 'list-video', ic_sc_later: 'clock' };
const BRAND_RED = '#FFC8102E';
// media buttons: drawable name -> material symbol file
const MATERIAL = { ic_replay_10_white: 'replay_10', ic_forward_30_white: 'forward_30', ic_n_close: 'close', ic_n_later: 'schedule' };

const SW = 2;

function parts(name) {
  const j = JSON.parse(fs.readFileSync(path.join(here, 'kubai', name + '.json'), 'utf8'));
  return j.w['2'].o.map((p) => ({ d: p.d, k: p.k, occ: !!p.occ }));
}

/** Circle "MxA r r ..." -> {cx, cy, r} for an occluding knob, else null. */
function circleOf(d) {
  const m = /^M([\d.]+) ([\d.]+)A([\d.]+) ([\d.]+) 0 1 1 ([\d.]+) ([\d.]+)/.exec(d);
  if (!m) return null;
  const x1 = +m[1], y1 = +m[2], r = +m[3], x2 = +m[5];
  return { cx: (x1 + x2) / 2, cy: y1, r };
}

/** Cut horizontal "Mx yLx2 y" lines where an occluding circle sits on them. */
function cutLines(list) {
  const knobs = list.filter((p) => p.occ).map((p) => circleOf(p.d)).filter(Boolean);
  if (!knobs.length) return list;
  return list.map((p) => {
    if (p.k !== 'line') return p;
    const m = /^M([\d.]+) ([\d.]+)L([\d.]+) ([\d.]+)$/.exec(p.d);
    if (!m || m[2] !== m[4]) return p;
    let segs = [[+m[1], +m[3]]];
    const y = +m[2];
    for (const k of knobs) {
      if (Math.abs(k.cy - y) > 0.01) continue;
      const a = k.cx - k.r - SW / 2, b = k.cx + k.r + SW / 2;   // the knob's outer stroke edge
      segs = segs.flatMap(([s, e]) => {
        const out = [];
        if (a > s) out.push([s, Math.min(e, a)]);
        if (b < e) out.push([Math.max(s, b), e]);
        return out;
      });
    }
    const f = (n) => +n.toFixed(3);
    return { ...p, d: segs.filter(([s, e]) => e - s > 0.01).map(([s, e]) => `M${f(s)} ${y}L${f(e)} ${y}`).join('') };
  });
}

function pathXml(p, color, indent) {
  if (p.k === 'solid') return `${indent}<path android:fillColor="${color}" android:pathData="${p.d}" />`;
  return `${indent}<path android:fillColor="#00000000" android:strokeColor="${color}" android:strokeWidth="${SW}"\n` +
    `${indent}    android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="${p.d}" />`;
}

const HEAD = (src) => `<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icons/gen-icons.mjs from ${src}; do not edit by hand -->\n`;

const written = [];
for (const [dr, [name, size]] of Object.entries(LINE)) {
  const ps = cutLines(parts(name));
  const xml = HEAD(`Kubai Icons "${name}" (MIT)`) +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${size}dp"\n    android:height="${size}dp"\n` +
    `    android:viewportWidth="24"\n    android:viewportHeight="24">\n` +
    ps.map((p) => pathXml(p, '#FFFFFFFF', '    ')).join('\n') + '\n</vector>\n';
  fs.writeFileSync(path.join(res, dr + '.xml'), xml);
  written.push(dr);
}
for (const [dr, name] of Object.entries(SHORTCUT)) {
  const ps = cutLines(parts(name));
  const xml = HEAD(`Kubai Icons "${name}" (MIT)`) +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="48dp"\n    android:height="48dp"\n` +
    `    android:viewportWidth="48"\n    android:viewportHeight="48">\n` +
    `    <path android:fillColor="#FFFFFFFF" android:pathData="M24,2a22,22 0 1,0 0.01,0z" />\n` +
    `    <group android:translateX="12" android:translateY="12">\n` +
    ps.map((p) => pathXml(p, BRAND_RED, '        ')).join('\n') + '\n    </group>\n</vector>\n';
  fs.writeFileSync(path.join(res, dr + '.xml'), xml);
  written.push(dr);
}
for (const [dr, name] of Object.entries(MATERIAL)) {
  const src = fs.readFileSync(path.join(here, 'material', name + '.xml'), 'utf8');
  const d = /android:pathData="([^"]+)"/.exec(src)[1];
  const xml = HEAD(`Material Symbols Rounded "${name}" FILL1 wght400 (Apache-2.0)`) +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n` +
    `    android:viewportWidth="960"\n    android:viewportHeight="960">\n` +
    `    <path android:fillColor="#FFFFFFFF" android:pathData="${d}" />\n</vector>\n`;
  fs.writeFileSync(path.join(res, dr + '.xml'), xml);
  written.push(dr);
}
console.log('wrote ' + written.length + ' drawables');
// paths for the two buttons injected into the m.youtube top bar (src/js/16-observer.js)
for (const n of ['settings', 'sliders']) console.log(n + ': ' + JSON.stringify(cutLines(parts(n)).map((p) => p.d)));
